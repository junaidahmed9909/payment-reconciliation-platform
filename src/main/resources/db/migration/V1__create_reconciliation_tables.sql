CREATE TABLE reconciliation_run (
    run_id        VARCHAR(64)   PRIMARY KEY,
    total         INTEGER       NOT NULL,
    match_rate    NUMERIC(5, 2) NOT NULL,
    parse_errors  INTEGER       NOT NULL,
    duration_ms   BIGINT        NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE reconciliation_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            VARCHAR(64)    NOT NULL,
    status            VARCHAR(32)    NOT NULL,
    reference         VARCHAR(128)   NOT NULL,
    bank_reference    VARCHAR(128),
    ledger_reference  VARCHAR(128),
    account_id        VARCHAR(64),
    currency          VARCHAR(3),
    bank_amount       NUMERIC(19, 2),
    ledger_amount     NUMERIC(19, 2),
    amount_difference NUMERIC(19, 2),
    reason            VARCHAR(512)   NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_record_run_id ON reconciliation_record (run_id);
CREATE INDEX idx_record_status ON reconciliation_record (status);
